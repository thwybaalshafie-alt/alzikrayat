import { useState } from 'react';
import { summarizeCommentsWithAi, getErrorMessage } from '../services/api';
import ErrorAlert from './ErrorAlert';

export default function AiSummaryBox({ photoId, commentCount }) {
  const [summary, setSummary] = useState('');
  const [modelUsed, setModelUsed] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  if (commentCount === 0) return null;

  const handleSummarize = async () => {
    setError('');
    try {
      setLoading(true);
      const data = await summarizeCommentsWithAi(photoId);
      setSummary(data.summary);
      setModelUsed(data.model || 'GLM-4.6V-Flash');
    } catch (err) {
      setError(getErrorMessage(err, 'Could not summarize comments right now.'));
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="ai-box" style={{ marginTop: '0.75rem', marginBottom: '1rem' }}>
      <div className="ai-box-header">
        <span className="ai-badge">✨ AI Comment Summary (Z.AI)</span>
        <button
          type="button"
          className="btn btn-ai btn-sm"
          onClick={handleSummarize}
          disabled={loading}
        >
          {loading ? 'Summarizing...' : summary ? 'Refresh Summary' : 'Summarize Comments'}
        </button>
      </div>

      <ErrorAlert message={error} onDismiss={() => setError('')} />

      {summary ? (
        <div>
          <p style={{ margin: 0, fontSize: '0.92rem', color: 'var(--text)' }}>{summary}</p>
          <span
            style={{
              display: 'inline-block',
              marginTop: '0.45rem',
              fontSize: '0.75rem',
              color: 'var(--text-muted)',
            }}
          >
            Generated by {modelUsed} from {commentCount}{' '}
            {commentCount === 1 ? 'comment' : 'comments'}
          </span>
        </div>
      ) : (
        <p style={{ margin: 0, fontSize: '0.85rem', color: 'var(--text-muted)' }}>
          Generate an instant AI summary of community discussion using Z.AI GLM-4.6V-Flash.
        </p>
      )}
    </div>
  );
}
